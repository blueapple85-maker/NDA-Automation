function build(){
  if(path.dirname(OUTPUT)!==ROOT||path.basename(OUTPUT)!=='dist')throw new Error('Unexpected build path');
  if(fs.existsSync(OUTPUT)){
    if(fs.lstatSync(OUTPUT).isSymbolicLink()||!fs.existsSync(path.join(OUTPUT,'.nda-static-build')))throw new Error('dist exists and was not created by this build. Move it before building.');
    fs.rmSync(OUTPUT,{recursive:true,force:true});
  }
  fs.mkdirSync(path.join(OUTPUT,'assets'),{recursive:true});
  fs.writeFileSync(path.join(OUTPUT,'.nda-static-build'),'Generated static demo only.\n');
  fs.writeFileSync(path.join(OUTPUT,'index.html'),html());
  fs.writeFileSync(path.join(OUTPUT,'assets/static-demo.js'),bundle());
  for(const name of ['studio.js','studio.css'])fs.copyFileSync(path.join(ROOT,'assets',name),path.join(OUTPUT,'assets',name));
  const licenses=['diff','fflate'].map(name=>`${name}\n${fs.readFileSync(path.join(ROOT,'node_modules',name,'LICENSE'),'utf8')}`).join('\n\n');
  fs.writeFileSync(path.join(OUTPUT,'THIRD-PARTY-LICENSES.txt'),licenses);
  console.log('Static demo built: dist/index.html (no API, no credentials, no runtime server)');
  return OUTPUT;
}
if(require.main===module)build();
module.exports={build};
