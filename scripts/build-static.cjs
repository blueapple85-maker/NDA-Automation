// A deliberately bounded CommonJS bundle: only these shared modules and the
// two browser-safe libraries can be included. AI, keys and server code cannot.
function bundle(){
  const modules=[],ids=new Map();
  const allowed=new Set(['assets/static-demo-entry.cjs','server/document.cjs','server/demo.cjs','server/errors.cjs','server/parties.cjs']);
  function add(filename){
    if(ids.has(filename))return ids.get(filename);
    const relative=path.relative(ROOT,filename).replace(/\\/g,'/');
    if(!allowed.has(relative)&&!relative.startsWith('node_modules/diff/libcjs/')&&relative!=='node_modules/fflate/lib/browser.cjs')throw new Error(`Not a public demo dependency: ${relative}`);
    const id=modules.length;ids.set(filename,id);modules.push('');
    const source=fs.readFileSync(filename,'utf8').replace(/require\(['"]([^'"]+)['"]\)/g,(_,specifier)=>{
      if(specifier==='@xmldom/xmldom')return 'browserXml';
      const next=specifier==='fflate'?path.join(ROOT,'node_modules/fflate/lib/browser.cjs'):
        specifier==='diff'?path.join(ROOT,'node_modules/diff/libcjs/diff/word.js'):
        specifier.startsWith('.')?require.resolve(path.resolve(path.dirname(filename),specifier)):null;
      if(!next)throw new Error(`Unsupported browser dependency: ${specifier}`);
      return `load(${add(next)})`;
    });
    modules[id]=`function(module,exports){\n${source}\n}`;return id;
  }
  const entry=add(path.join(ROOT,'assets/static-demo-entry.cjs'));
  return `/* Generated by scripts/build-static.cjs. Dependency licenses: THIRD-PARTY-LICENSES.txt */
(()=>{'use strict';
const Buffer={from:value=>new Uint8Array(value)};
const browserXml={XMLSerializer:window.XMLSerializer,DOMParser:class{
  parseFromString(source,type){const parsed=new window.DOMParser().parseFromString(source,type);if(parsed.getElementsByTagName('parsererror').length)throw new Error('문서 XML을 읽을 수 없습니다. 손상되지 않은 체험용 DOCX를 사용해 주세요.');return parsed;}
}};
const modules=[${modules.join(',\n')}],cache={};
function load(id){if(cache[id])return cache[id].exports;const module={exports:{}};cache[id]=module;modules[id](module,module.exports);return module.exports;}
load(${entry});
})();\n`;
}
